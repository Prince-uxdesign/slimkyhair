/**
 * Determine root path prefix based on window location depth
 */
export function getRootPath() {
  const path = window.location.pathname;
  if (path.includes('/category/') || path.includes('/product/')) {
    // If inside a sub-path like /category/hair-oils/ or /product/nourishing-scalp-oil/
    const depth = path.split('/').filter(Boolean).length;
    if (depth >= 2) return '../../';
    if (depth === 1) return '../';
  } else if (path.includes('/shop/') || path.includes('/search/') || path.includes('/wishlist/')) {
    return '../';
  }
  return '';
}

/**
 * Build a responsive <picture> element for a catalog photograph.
 *
 * Serves right-sized derivatives generated by scripts/optimize-images.py:
 * WebP first (<source>), resized JPEGs + the untouched original as the
 * <img> fallback. Alt text, width/height (CLS guard) and lazy discipline
 * are set by the caller and never altered here.
 *
 * All catalog photographs are 896px wide portraits; derivatives exist at
 * 480w / 768w plus a full-width WebP beside each original.
 */
export function responsivePictureHTML({ root, src, alt, imgClass, sizes, eager = false, fetchPriority = null, width = 600, height = 750 }) {
  const webpFull = `${root}${src.replace(/\.(jpe?g)$/i, '.webp')}`;
  const stem = `${root}${src.replace(/\.(jpe?g)$/i, '')}`;
  const loadingAttr = eager ? 'loading="eager"' : 'loading="lazy"';
  const fetchAttr = fetchPriority ? `fetchpriority="${fetchPriority}"` : '';
  return `<picture>
            <source type="image/webp" srcset="${stem}-480.webp 480w, ${stem}-768.webp 768w, ${webpFull} 896w" sizes="${sizes}">
            <img
              src="${root}${src}"
              srcset="${stem}-480.jpg 480w, ${stem}-768.jpg 768w, ${root}${src} 896w"
              sizes="${sizes}"
              alt="${alt}"
              class="${imgClass}"
              ${loadingAttr}
              decoding="async"
              ${fetchAttr}
              width="${width}"
              height="${height}"
            >
          </picture>`;
}

/**
 * Render a standardized, accessible product card HTML
 * @param {Object} product - Product object from catalog-data.js
 * @param {Object} options - Custom rendering options (e.g. rootPrefix)
 * @returns {string} - HTML string
 */
export function createCatalogCardHTML(product, options = {}) {
  const root = options.rootPrefix !== undefined ? options.rootPrefix : getRootPath();
  const productUrl = `${root}product/${product.slug}/`;
  const defaultVariant = product.variants && product.variants.length > 0 ? product.variants[0] : null;
  const priceDisplay = defaultVariant ? defaultVariant.priceFormatted : (product.price || "₦0");
  const variantText = product.variants && product.variants.length > 1
    ? `${product.variants.length} Sizes Available`
    : (defaultVariant ? defaultVariant.size : (product.size || "Standard"));

  // Check wishlist state
  const isSaved = isInWishlist(product.id);
  const imageSrc = `${root}${product.images.packaging}`;

  // Milestone C20.12: Live availability badge, sourced through inventoryService
  // (never a stale catalog literal) so it stays synchronized with checkout deductions.
  const liveStock = defaultVariant
    ? inventoryService.getEffectiveStock(defaultVariant.sku, defaultVariant.stock)
    : null;
  const availability = liveStock !== null ? getAvailabilityLabel(liveStock) : null;
  const isSoldOut = availability ? availability.className === 'out-of-stock' : false;

  return `
    <article class="product-card" id="product-${product.id}" data-product-id="${product.id}" data-product-slug="${product.slug}">
      <div class="product-card-media media-frame media-frame-product">
        ${product.badge ? `<span class="badge ${product.badge.class} product-card-badge">${product.badge.text}</span>` : ''}
        
        <button 
          type="button" 
          class="product-card-wishlist ${isSaved ? 'is-active' : ''}" 
          aria-label="${isSaved ? 'Remove ' + product.name + ' from wishlist' : 'Save ' + product.name + ' to wishlist'}" 
          data-product-id="${product.id}"
          data-saved="${isSaved ? 'true' : 'false'}"
        >
          <svg viewBox="0 0 24 24" fill="${isSaved ? 'currentColor' : 'none'}" stroke="currentColor" aria-hidden="true">
            <path d="M19 14c1.49-1.46 3-3.21 3-5.5A5.5 5.5 0 0 0 16.5 3c-1.76 0-3 .5-4.5 2-1.5-1.5-2.74-2-4.5-2A5.5 5.5 0 0 0 2 8.5c0 2.3 1.5 4.05 3 5.5l7 7Z"/>
          </svg>
        </button>

        <a href="${productUrl}" class="product-card-image-link" tabindex="-1" aria-hidden="true">
          ${responsivePictureHTML({
            root,
            src: product.images.packaging,
            alt: `${product.name} - ${product.descriptor}`,
            imgClass: 'product-card-image media-img media-img-center',
            sizes: '(max-width: 480px) 50vw, (max-width: 1024px) 33vw, 25vw',
          })}
        </a>
      </div>

      <div class="product-card-content">
        <div class="product-card-category">${product.category}</div>
        <h3 class="product-card-title">
          <a href="${productUrl}">${product.name}</a>
        </h3>
        <p class="product-card-descriptor">${product.descriptor}</p>
        <div class="product-card-variant">${variantText}</div>

        <div class="product-card-rating">
          <div class="product-card-stars">
            ${renderStarsHTML(product.rating)}
          </div>
          <span class="product-card-review-count">${product.rating.toFixed(1)} (${product.reviewCount})</span>
        </div>

        <div class="product-card-actives">
          <svg class="product-card-actives-icon" viewBox="0 0 24 24" fill="none" stroke="currentColor" aria-hidden="true"><path d="M12 22c0-6-4-9-8-10M12 22c0-6 4-9 8-10M12 22V10M12 10C12 6 9 3 6 2M12 10c0-4 3-7 6-8"/></svg>
          <span>Natural Actives</span>
        </div>

        ${availability ? `
          <div class="product-card-availability ${availability.className}">
            <span class="product-card-availability-dot" aria-hidden="true"></span>
            <span class="product-card-availability-text">${availability.label}</span>
          </div>
        ` : ''}

        <div class="product-card-footer">
          <span class="product-card-price">${priceDisplay}</span>
        </div>

        <div class="product-card-quickadd">
          <button
            type="button"
            class="btn btn-primary btn-full btn-quick-add"
            data-product-id="${product.id}"
            data-product-name="${product.name}"
            data-product-price="${priceDisplay}"
            data-product-image="${imageSrc}"
            data-product-size="${defaultVariant ? defaultVariant.size : ''}"
            data-variant-sku="${defaultVariant ? defaultVariant.sku : ''}"
            ${isSoldOut ? 'disabled' : ''}
          >
            ${isSoldOut ? 'Out of Stock' : `Quick Add · ${priceDisplay}`}
          </button>
        </div>
      </div>
    </article>
  `;
}

/**
 * Render loading skeleton cards to prevent layout shift
 * @param {number} count - Number of skeleton cards to generate
 * @returns {string} - HTML string
 */
export function createSkeletonCardsHTML(count = 8) {
  return Array(count).fill(0).map(() => `
    <article class="product-card skeleton-card" aria-hidden="true">
      <div class="skeleton-media skeleton-pulse"></div>
      <div class="product-card-content">
        <div class="skeleton-line skeleton-line-eyebrow skeleton-pulse"></div>
        <div class="skeleton-line skeleton-line-title skeleton-pulse"></div>
        <div class="skeleton-line skeleton-line-desc skeleton-pulse"></div>
        <div class="skeleton-line skeleton-line-meta skeleton-pulse"></div>
        <div class="skeleton-line skeleton-line-footer skeleton-pulse"></div>
        <div class="skeleton-button skeleton-pulse"></div>
      </div>
    </article>
  `).join('');
}

/**
 * Attach global event delegation for wishlist and quick-add actions
 * @param {HTMLElement} container - Container holding product cards
 * @param {Object} callbacks - Optional callbacks
 */
export function initCardInteractions(container = document, callbacks = {}) {
  // Wishlist toggle
  const wishlistBtns = container.querySelectorAll('.product-card-wishlist');
  wishlistBtns.forEach(btn => {
    btn.addEventListener('click', (e) => {
      e.preventDefault();
      e.stopPropagation();
      const pid = btn.getAttribute('data-product-id');
      const { saved } = toggleWishlist(pid);
      syncWishlistUI();

      if (callbacks.onWishlistToggle) {
        callbacks.onWishlistToggle(pid, saved);
      }
    });
  });

  // Quick Add Button
  const quickAddBtns = container.querySelectorAll('.btn-quick-add');
  quickAddBtns.forEach(btn => {
    if (btn.disabled) return; // Already out of stock at render time — nothing to wire up.

    btn.addEventListener('click', (e) => {
      e.preventDefault();
      e.stopPropagation();

      const originalText = btn.textContent;
      const pid = btn.getAttribute('data-product-id');
      const pVariant = btn.getAttribute('data-variant-sku') || btn.getAttribute('data-product-size') || null;

      // Add to centralized cart store with canonical product & variant resolution.
      // Milestone C20.12: never claim success blindly — inventory may have sold
      // out since this card was rendered, so branch on the actual result.
      const result = addItem(pid, 1, pVariant);

      if (!result.success) {
        btn.textContent = 'Out of Stock';
        btn.disabled = true;
        btn.classList.remove('btn-primary');
        btn.classList.add('btn-secondary');
        return;
      }

      btn.textContent = result.stockLimitReached ? 'Max Stock Added ✓' : 'ADDED TO BAG ✓';
      btn.classList.add('btn-secondary');
      btn.classList.remove('btn-primary');
      btn.disabled = true;

      setTimeout(() => {
        btn.textContent = originalText;
        btn.classList.remove('btn-secondary');
        btn.classList.add('btn-primary');
        btn.disabled = false;

        // Open Cart Drawer preview
        openCartDrawer();
      }, 400);
    });
  });
}

